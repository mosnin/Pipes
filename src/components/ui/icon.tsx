/* ==========================================================================
   THE ICON SET — Phosphor, at `bold` weight, and nothing else.

   WHY THIS FILE EXISTS. anti-slop.md rule 9 says a default icon set dropped
   in everywhere is a finding and that the choice needs a stated rationale.
   This is the rationale, and it is a measurement rather than a taste: crop
   the reference's rail at 3x and its glyphs are SOLID — a filled house, a
   filled tray, a filled tag. Lucide has one weight and it is a hairline
   outline. At 16px on a 28px row that difference is the loudest single
   thing separating a recreation from the thing it recreates, and no amount
   of correct spacing hides it. Phosphor ships the same coverage in six
   weights, so the weight becomes a decision we make once, here.

   TWO WEIGHTS, AND WHERE THE LINE IS. Crop the reference at 3x and its
   rail is flooded — a solid house, a solid tray, a solid tag — while the
   magnifier eight rows to the right, inside the table card, is a hairline
   outline. That is not an inconsistency, it is the rule: NAVIGATION is
   filled and marks where you are; everything inside the page is an
   outline and marks what you can do. So `regular` is the product's
   weight, and `NavIcons` flips it to `fill` around the rail. Getting the
   two the wrong way round is visible immediately: a filled magnifier is a
   solid disc with a handle, which reads as a lollipop rather than as
   search. That was the first attempt.

   HOW TO USE IT. Import from here, never from "@phosphor-icons/react" and
   never from "@/components/ui/icon": one import path is what keeps the weight a
   single decision instead of 190 of them. The exported names are lucide's,
   because that is the vocabulary 115 files already speak and renaming them
   would have made this change unreviewable.

   `size` and `className` work as they did. `strokeWidth` is inert — weight
   is set here — and is left on the call sites it is already on rather than
   swept out of 115 files in the same commit.
   ========================================================================== */

/** Everything inside the page. */
export const ICON_WEIGHT = "regular" as const;
/** Navigation, and only navigation. */
export const NAV_ICON_WEIGHT = "fill" as const;

export type Icon = PhosphorIcon;
/** The name 115 call sites already use for "a component that is an icon". */
export type LucideIcon = PhosphorIcon;
export type { IconProps };

/**
 * Sets the weight for every icon beneath it. Individual icons may still
 * override it — a filled status dot, for instance — by passing `weight`.
 */
export function IconProvider({ children }: { children: ReactNode }): ReactNode {
  return (
    <IconContext.Provider value={{ weight: ICON_WEIGHT }}>
      {children}
    </IconContext.Provider>
  );
}

/** Wraps the rail, and nothing else. Inside it, icons are filled. */
export function NavIcons({ children }: { children: ReactNode }): ReactNode {
  return (
    <IconContext.Provider value={{ weight: NAV_ICON_WEIGHT }}>
      {children}
    </IconContext.Provider>
  );
}

